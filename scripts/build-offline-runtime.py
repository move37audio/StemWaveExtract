#!/usr/bin/env python3
"""Build only ignored release resources; never use a user's installed runtime."""
from pathlib import Path
import hashlib
import os
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]
BOOTSTRAP = ROOT / 'builds/first-run-runtime'
BUILD = ROOT / 'builds/offline-prototype'
DEST = ROOT / 'vendor/runtime'
FFMPEG_SHA = '40973d44970dbc83ef302b0609f2e74982be2d85916dd2ee7472d30678a7abe6'

def run(*args, **kwargs):
    subprocess.run(args, check=True, **kwargs)

def sha(path):
    digest = hashlib.sha256()
    with path.open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            digest.update(block)
    return digest.hexdigest()

run(str(ROOT / 'scripts/fetch-uv.sh'))
run('bash', str(ROOT / 'engine/setup.sh'), env=dict(os.environ,
    STEMWAVE_RUNTIME=str(BOOTSTRAP), UV=str(ROOT / 'vendor/uv'), PYTHONDONTWRITEBYTECODE='1'))
BUILD.mkdir(parents=True, exist_ok=True)
archive = BUILD / 'ffmpeg-7.1.tar.xz'
if not archive.exists():
    run('curl', '-fL', '--retry', '3', 'https://ffmpeg.org/releases/ffmpeg-7.1.tar.xz', '-o', str(archive))
if sha(archive) != FFMPEG_SHA:
    raise RuntimeError('FFmpeg source checksum mismatch')
source = BUILD / 'ffmpeg-7.1'
if not source.exists():
    run('tar', '-xf', str(archive), '-C', str(BUILD))
flags = ['--disable-autodetect', '--disable-network', '--disable-doc', '--disable-debug',
         '--disable-ffplay', '--disable-ffprobe', '--disable-gpl', '--disable-nonfree',
         '--disable-videotoolbox', '--disable-audiotoolbox']
with (BUILD / 'ffmpeg-configure.log').open('w') as log:
    run('./configure', *flags, cwd=source, stdout=log, stderr=subprocess.STDOUT)
with (BUILD / 'ffmpeg-build.log').open('w') as log:
    run('make', '-j8', cwd=source, stdout=log, stderr=subprocess.STDOUT)
# This destination is generated by this script, never user data.
if DEST.exists():
    shutil.rmtree(DEST)
DEST.mkdir(parents=True)
base = next((BOOTSTRAP / 'python').glob('cpython-*'))
ignore = shutil.ignore_patterns('__pycache__', '*.pyc', 'imageio_ffmpeg', 'imageio_ffmpeg-*.dist-info')
shutil.copytree(base, DEST / 'python', symlinks=True, ignore=ignore)
shutil.copytree(BOOTSTRAP / 'venv/lib/python3.10/site-packages',
    DEST / 'python/lib/python3.10/site-packages', dirs_exist_ok=True, symlinks=True, ignore=ignore)
config = DEST / 'python/lib/python3.10/_sysconfigdata__darwin_darwin.py'
text = config.read_text().replace(str(base), '/opt/stemwave/python')
text += '\nimport sys\nbuild_time_vars = {k: v.replace("/opt/stemwave/python", sys.base_prefix) if isinstance(v, str) else v for k, v in build_time_vars.items()}\n'
config.write_text(text)
run('install_name_tool', '-id', '@rpath/libpython3.10.dylib', str(DEST / 'python/lib/libpython3.10.dylib'))
(DEST / 'bin').mkdir()
shutil.copy2(source / 'ffmpeg', DEST / 'bin/ffmpeg')
(DEST / 'models').mkdir()
for name in ['BS-Rofo-SW-Fixed.ckpt', 'BS-Rofo-SW-Fixed.yaml', 'beat_this-final0.ckpt']:
    shutil.copy2(BOOTSTRAP / 'models' / name, DEST / 'models' / name)
licenses = DEST / 'licenses'; licenses.mkdir()
shutil.copy2(source / 'COPYING.LGPLv2.1', licenses / 'FFmpeg-LGPL-2.1.txt')
(licenses / 'FFmpeg-BUILD.txt').write_text('FFmpeg 7.1, unmodified source.\nSource SHA-256: ' + FFMPEG_SHA + '\nConfigure: ./configure ' + ' '.join(flags) + '\nBuild: make -j8\nSource archive: https://github.com/move37audio/StemWaveExtract/releases/download/v0.1.0/ffmpeg-7.1.tar.xz\n')
# uv relocates these two interpreter paths; restore relocatability before signing.
for path in DEST.rglob('*'):
    if not path.is_file() or path.is_symlink():
        continue
    with path.open('rb') as stream:
        magic = stream.read(4)
    if magic in [b'\xcf\xfa\xed\xfe', b'\xce\xfa\xed\xfe', b'\xca\xfe\xba\xbe', b'\xbe\xba\xfe\xca']:
        run('codesign', '--force', '--sign', '-', str(path), stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
run(str(DEST / 'python/bin/python3.10'), '-I', '-B', '-c',
    'import torch, scipy, yaml, einops, rotary_embedding_torch, beat_this; print("Bundled runtime imports: PASS")')
run(str(DEST / 'bin/ffmpeg'), '-v', 'error', '-f', 'lavfi', '-i', 'sine=duration=0.1', '-f', 'null', '-')
release = ROOT / 'builds/release'; release.mkdir(parents=True, exist_ok=True)
shutil.copy2(archive, release / archive.name)
print('Offline runtime assembled with both checkpoints and standalone LGPL FFmpeg.')
